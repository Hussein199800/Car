const findRaw = (m, re) => m?.raw?.find((r) => re.test(String(r.title).toLowerCase()));
const rawNum = (m, re) => num(findRaw(m, re)?.val);
const rawStr = (m, re) => String(findRaw(m, re)?.val ?? '').toLowerCase();

// نصائح مخصّصة: كل نصيحة مبنية على قيمة فعلية من جهازك، ولا تظهر إن لم تتوفر القيمة
export function smartTips(m, prefs) {
  if (!m) return [];
  const out = [];
  const add = (level, title, body) => out.push({ level, title, body });

  if (m.stale) {
    add('bad', 'الإنفرتر لا يرسل قراءات', 'تأكد أن الإنفرتر يعمل، وأن الإنترنت في البيت متوفر. إذا كان الإنفرتر يعمل فجرّب إعادة تشغيل الراوتر أو فصل وحدة الواي فاي وإعادتها.');
    return out; // باقي النصائح تعتمد على قراءات حيّة
  }

  // نفس الحدود التي اختارها المستخدم للتنبيهات، حتى لا تتعارض النصيحة مع التنبيه
  const over = prefs.overloadPct ?? 80;
  if (m.loadPct !== null && m.loadPct >= over) add('bad', `الحمل مرتفع (${fmt.pct(m.loadPct)})`, 'أطفئ بعض الأجهزة الكبيرة الآن، فالاستمرار قرب الحد الأقصى يرفع حرارة الإنفرتر وقد يؤدي لإطفائه.');
  else if (m.loadPct !== null && m.loadPct >= over - 20) add('warn', `الحمل ${m.loadPct}% من قدرة الإنفرتر`, 'لا تضف أجهزة ذات تيار إقلاع عالٍ (مكيف أو مضخة) الآن قبل إطفاء جهاز آخر.');

  if (m.soc !== null && m.soc <= (prefs.lowSoc ?? 30) && (m.batW ?? 0) <= 0) add('bad', `البطارية منخفضة (${fmt.pct(m.soc)})`, 'خفّف الأحمال لتبقى البطارية لأطول وقت، وتجنّب التفريغ الكامل لأنه يُقصّر عمر الليثيوم.');

  const h = new Date().getHours();
  if (h >= 10 && h <= 14 && m.pvW !== null && m.pvW < 50 && m.pv1V !== null && m.pv1V < 50) {
    add('warn', 'لا يوجد إنتاج من الألواح وقت الظهر', 'إذا كان الجو مشمساً فتحقق من قاطع الألواح والتوصيلات، أو من وجود عطل في السلسلة.');
  }
  if (h >= 10 && h <= 14 && m.pvW !== null && m.pvW > 300 && m.soc !== null && m.soc >= 95) {
    add('ok', 'البطارية ممتلئة والشمس قوية', 'هذا أفضل وقت لتشغيل الغسالة أو المكواة أو سخان الماء من طاقة الشمس مباشرة.');
  }

  const gr = m.gridRatedV || 230;
  if (m.gridV !== null && m.gridOn && (m.gridV < gr * 0.85 || m.gridV > gr * 1.09)) {
    add('warn', `جهد كهرباء الشبكة غير مستقر (${m.gridV} فولت)`, `الجهد بعيد عن القيمة الاسمية (${gr} فولت). نطاق الدخل «UPS» يحمي الأجهزة الحساسة بفصل الكهرباء السيئة أسرع.`);
  }

  const out1 = rawStr(m, /^output source priority/);
  if (/solar bat utility|sbu/.test(out1) && m.gridOn && m.soc !== null && m.soc < 35 && (m.batW ?? 0) < 0) {
    add('info', 'الكهرباء متوفرة والبطارية تنخفض', 'أولوية الخرج لديك SBU، لذا يستخدم الإنفرتر البطارية حتى مع وجود الكهرباء. إذا كانت الانقطاعات متوقعة الليلة فقد تفضّل SUB مؤقتاً لحفظ البطارية.');
  }

  const type = rawStr(m, /^battery type/);
  const bulk = rawNum(m, /^battery bulk voltage/);
  const flt = rawNum(m, /^battery float voltage/);
  const cells = { 12: 4, 24: 8, 48: 16 }[m.ratedV];
  if (cells && /lib|lithium/.test(type) && flt !== null && bulk !== null && flt >= cells * 3.5 && flt >= bulk - 0.2) {
    const lo = (cells * 3.35).toFixed(1), hi = (cells * 3.45).toFixed(1);
    add('info', `جهد الشحن العائم ${flt} فولت مساوٍ للسريع`, `إذا كانت بطاريتك LiFePO4 بـ${cells} خلية فالشائع ضبط الشحن العائم بين ${lo} و${hi} فولت لإطالة عمرها. تأكد من القيمة الموصى بها في مواصفات بطاريتك قبل أي تغيير، فبعض البطاريات المتصلة بالإنفرتر عبر BMS تتحكم بالشحن بنفسها.`);
  }

  const re = rawNum(m, /^battery re-?charge voltage/);
  const rd = rawNum(m, /^battery re-?discharge voltage/);
  if (re !== null && rd !== null) add('info', 'متى ينتقل الإنفرتر بين البطارية والكهرباء؟', `عند هبوط البطارية إلى ${re} فولت ينتقل لكهرباء الشبكة (إن وُجدت)، ويعود للبطارية بعد شحنها إلى ${rd} فولت.`);

  const maxAc = rawNum(m, /^max ac charging current/);
  if (maxAc !== null && m.ratedV) add('info', `الشحن من الكهرباء حتى ${maxAc} أمبير`, `أي ما يقارب ${Math.round((maxAc * m.ratedV) / 100) / 10} كيلوواط من كهرباء الشبكة فوق استهلاك البيت. قلّل هذا التيار إذا كانت أمبيرية الكهرباء عندك محدودة.`);

  if (prefs.batteryAh && m.disA) {
    const c = m.disA / prefs.batteryAh;
    if (c > 0.5) add('warn', `سحب عالٍ من البطارية (${c.toFixed(2)}C)`, `التيار ${m.disA} أمبير يتجاوز نصف سعة بطاريتك (${prefs.batteryAh} أمبير ساعة). السحب العالي المستمر يرفع الحرارة ويقلل العمر.`);
  } else if (!prefs.batteryAh) {
    add('info', 'أدخل سعة بطاريتك', 'من «المزيد ← الإعدادات» لتحصل على تقدير المدة المتبقية ونصائح عن تيار السحب المناسب.');
  }

  if (m.invTemp != null && m.invTemp >= (prefs.tempInv ?? 75)) add('warn', `حرارة الإنفرتر مرتفعة (${m.invTemp}°م)`, 'تأكد من التهوية حول الإنفرتر ونظافة المراوح، وخفّف الأحمال.');
  if (m.batTemp != null && m.batTemp >= (prefs.tempBat ?? 50)) add('warn', `حرارة البطارية مرتفعة (${m.batTemp}°م)`, 'أبعد البطارية عن الشمس ومصادر الحرارة، وخفّف تيار الشحن والسحب حتى تبرد.');

  if (!out.length) add('ok', 'كل شيء يبدو جيداً', 'لا توجد ملاحظات على قراءات جهازك الحالية. استمر بمتابعة التقارير أسبوعياً.');
  return out;
}

export function tipOfDay() {
  const all = TIP_SECTIONS.flatMap((s) => s.tips.map(([title, body]) => ({ title, body, section: s.title })));
  const day = Math.floor(Date.now() / 864e5);
  return all[day % all.length];
}

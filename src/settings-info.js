const norm = (s) => String(s ?? '').trim().toLowerCase().replace(/[._]/g, ' ').replace(/\s+/g, ' ');

export function settingInfo(name) {
  const n = norm(name);
  return SETTINGS.find((x) => x.re.test(n)) || null;
}

export function optionAr(val) {
  const n = norm(val);
  if (OPTIONS[n]) return OPTIONS[n];
  // قيم مثل «50Hz» أو «230V» تبقى كما هي، والكلمات المعروفة تُترجم جزئياً
  const words = n.split(' ');
  if (words.length > 1 && words.every((w) => OPTIONS[w])) return words.map((w) => OPTIONS[w]).join(' ');
  return String(val);
}

// «48.0~58.4V» أو «0-900min» → [min, max] ، وإلا null
export function hintRange(hint) {
  const m = String(hint ?? '').match(/^\s*(-?\d+(?:\.\d+)?)\s*[~\-–—]\s*(-?\d+(?:\.\d+)?)\s*[A-Za-z%°]*\s*$/);
  if (!m) return null;
  const a = Number(m[1]), b = Number(m[2]);
  return [Math.min(a, b), Math.max(a, b)];
}
